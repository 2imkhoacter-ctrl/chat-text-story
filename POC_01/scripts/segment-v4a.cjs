const fs = require('node:fs');
const path = require('node:path');
const { probeDuration, detectPhraseRanges, extractClip } = require('./segment-audio.cjs');
const { buildPhraseTimeline } = require('../src/phrase-timeline.cjs');
const root = path.resolve(__dirname, '..');
const round = (value) => Number(value.toFixed(6));

const segmentV4A = () => {
  const baseline = JSON.parse(fs.readFileSync(path.join(root, 'video.config.json'), 'utf8'));
  const config = { ...baseline, ...JSON.parse(fs.readFileSync(path.join(root, 'video.v4a.config.json'), 'utf8')) };
  const source = path.resolve(root, config.audio);
  if (!fs.existsSync(source)) throw new Error(`V4A input is missing: ${source}. Place the new full TTS here or set audio in video.v4a.config.json.`);
  const duration = probeDuration(source);
  const ranges = detectPhraseRanges(config, duration);
  if (!ranges.length) throw new Error('No speech phrases detected. Review silence settings.');
  const outputDir = path.resolve(root, config.generatedAudioDir);
  fs.mkdirSync(outputDir, { recursive: true });
  const phrases = ranges.map((range, index) => {
    const id = `phrase-${String(index + 1).padStart(3, '0')}`;
    const audioFile = `voice_${String(index + 1).padStart(3, '0')}.wav`;
    // Preserve consonants/decays with small handles, capped at silence midpoints.
    const sourceStart = round(Math.max(index ? (ranges[index - 1].end + range.start) / 2 : 0, range.start - config.phraseHeadPaddingSeconds));
    const sourceEnd = round(Math.min(index < ranges.length - 1 ? (range.end + ranges[index + 1].start) / 2 : duration, range.end + config.phraseTailPaddingSeconds));
    const phrase = { id, label: `Phrase ${index + 1}`, audioFile,
      relativeAudioFile: path.relative(path.join(root, 'public'), path.join(outputDir, audioFile)).replace(/\\/g, '/'),
      detectedStart: range.start, detectedEnd: range.end, sourceStart, sourceEnd,
      pauseAfter: config.phrasePauses[id] ?? 0,
      maskStopY: config.maskStops[Math.min(index, config.maskStops.length - 1)].y,
      maskStatus: index < config.maskStops.length ? config.maskStops[index].status : 'unmapped-hold-last',
      reviewWarnings: [],
    };
    extractClip(config, phrase, path.join(outputDir, audioFile));
    phrase.clipDuration = round(probeDuration(path.join(outputDir, audioFile)));
    if (!(phrase.clipDuration > 0)) throw new Error(`Empty voice file: ${audioFile}`);
    if (range.end - range.start < 0.15) phrase.reviewWarnings.push('Detected speech shorter than 150ms; review before accepting.');
    if (range.end - range.start > 8) phrase.reviewWarnings.push('Detected speech longer than 8s; review for potentially merged phrases.');
    return phrase;
  });
  const manifest = buildPhraseTimeline({ timelineModel: 'voice-hold-gap-v1', sampleMode: false,
    generatedAt: new Date().toISOString(), sourceAudio: config.audio, sourceDurationSeconds: duration,
    silenceThresholdDb: config.silenceThresholdDb, minimumSilenceDurationSeconds: config.minimumSilenceDurationSeconds,
    phraseHeadPaddingSeconds: config.phraseHeadPaddingSeconds, phraseTailPaddingSeconds: config.phraseTailPaddingSeconds,
    initialMarginSeconds: config.initialMarginSeconds, normalGapSeconds: config.defaultPauseAfterSeconds, phrases,
  }, { initialMargin: config.initialMarginSeconds, normalGap: config.defaultPauseAfterSeconds });
  fs.writeFileSync(path.resolve(root, config.timingManifest), `${JSON.stringify(manifest, null, 2)}\n`);
  // Distinct source nodes keep every voice independently visible in Studio's
  // timeline instead of collapsing a mapped Audio node as duplicated instances.
  const nodes = phrases.map((_, index) => `    React.createElement(Audio, { key: phrases[${index}].id, name: phrases[${index}].id, src: staticFile(phrases[${index}].relativeAudioFile), from: phrases[${index}].timelineStart * fps, durationInFrames: phrases[${index}].clipDuration * fps })`);
  fs.writeFileSync(path.join(root, 'src/v4a-audio.jsx'), `// Generated by segment-v4a.cjs. Timing always comes from the dynamic manifest.\nconst React = require('react');\nconst { Audio } = require('@remotion/media');\nconst { staticFile, useVideoConfig } = require('remotion');\nmodule.exports = ({ phrases }) => {\n  const { fps } = useVideoConfig();\n  return React.createElement(React.Fragment, null,\n${nodes.join(',\n')}\n  );\n};\n`);
  console.log(`${duration.toFixed(6)}s input; ${phrases.length} phrases / WAV files; ${config.generatedAudioDir}`);
  return manifest;
};

if (require.main === module) {
  try { segmentV4A(); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { segmentV4A };
